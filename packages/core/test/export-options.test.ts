// Export options (PRD F5.3): every option changes only how the code is written.
// The variants must load the default code's weights (same state_dict keys) and
// compute the same outputs; split files must import as a package; the self-test
// must pass when run as a script.
import { beforeAll, describe, expect, it } from 'vitest';
import { analyzeProject, entryModule, generateCode, generateFiles, parseProject, type ExportOptions, type LoomProject } from '../src';
import { mlp, resnet, sequentialHead, twoHeads, withCodeBlock } from './fixtures';
import { hasTorch, importMany, inputShapesOf, runPython } from './python';

const FIXTURES: Record<string, () => LoomProject> = { mlp, resnet, sequentialHead, twoHeads, withCodeBlock };

const VARIANTS: Record<string, ExportOptions> = {
  plain: { shapeComments: false, typeHints: false },
  nested: { nesting: 3 },
  sequential: { sequentialRepeats: true },
  documented: { docstrings: true, header: true, selfTest: true },
  everything: { shapeComments: false, typeHints: false, nesting: 1, sequentialRepeats: true, docstrings: true, header: true, selfTest: true },
};

const code = (p: LoomProject, options: ExportOptions) => generateCode({ ...p, exportOptions: options }).code;

describe('export options', () => {
  it('leave the code as it was when absent or default', () => {
    for (const make of Object.values(FIXTURES)) {
      const p = make();
      expect(code(p, {})).toBe(generateCode(p).code);
      expect(code(p, { shapeComments: true, typeHints: true, nesting: 0, sequentialRepeats: false, splitFiles: false })).toBe(generateCode(p).code);
    }
  });

  it('drop shape comments and annotations', () => {
    const text = code(resnet(), VARIANTS.plain!);
    expect(text).not.toMatch(/# \[/);
    expect(text).not.toMatch(/: torch\.Tensor|-> |: int/);
    expect(text).toContain('def __init__(self, num_classes=10, width=16, depth=2):');
  });

  it('nest single-use calls up to the depth asked for, never reordering statements', () => {
    // x is also the residual, so the chain gets its own name; the addition stays after conv2.
    expect(code(resnet(), { nesting: 3 })).toContain('conv1 = self.conv2(F.relu(self.bn1(self.conv1(x))))');
    expect(code(resnet(), { nesting: 3 })).toContain('return F.relu(self.bn2(conv1) + x)');
    expect(code(resnet(), { nesting: 1 })).toContain('conv1 = self.bn1(self.conv1(x))');
    expect(code(resnet(), { nesting: 1 })).toContain('x = torch.flatten(self.pool(x), 1)');
    // fc1 and fc2 both read x: neither is nested into the other's consumer out of order.
    const heads = code(twoHeads(), { nesting: 3 });
    expect(heads.split('\n').filter((l) => l.includes('self.')).length).toBeGreaterThan(0);
  });

  it('write repeats with one input as nn.Sequential, called once', () => {
    const text = code(resnet(), VARIANTS.sequential!);
    expect(text).toContain('self.blocks = nn.Sequential(*[ResBlock(width) for _ in range(depth)])');
    expect(text).toMatch(/x = self\.blocks\(x\)/);
    expect(text).not.toContain('for block in self.blocks');
  });

  it('add docstrings with parameter counts, a header and a self-test', () => {
    const text = code(resnet(), VARIANTS.documented!);
    expect(text.split('\n')[0]).toMatch(/^# .*generated by NeuroLoom/);
    expect(text).toContain('class ResBlock(nn.Module):\n    """ResBlock: ');
    expect(text).toContain('if __name__ == "__main__":\n    model = ResNet()\n    x = torch.randn(1, 3, 32, 32)\n    out = model(x)\n    assert tuple(out.shape) == (1, 10), out.shape');
  });

  it('call the self-test without an optional argument that has no example shape', () => {
    const p = mlp();
    const entry = entryModule(p);
    entry.nodes.targets = { id: 'targets', kind: 'input', type: 'neuroloom.Input', name: 'targets', params: { shape: { literal: '' } } };
    entry.interface = { ...entry.interface, inputs: [...entry.interface.inputs, 'targets'], defaults: { targets: 'None' } };
    const text = code(p, { selfTest: true });
    expect(text).toContain('def forward(self, x: torch.Tensor, targets=None)');
    expect(text).toMatch(/out = model\(x\)\n/);
    expect(text).not.toContain('targets = torch');
  });

  it('put from __future__ imports first, in one file and in a package', () => {
    const p = { ...mlp(), preamble: 'import math\nfrom __future__ import annotations' };
    expect(code(p, {}).split('\n')[0]).toBe('from __future__ import annotations');
    const files = generateFiles({ ...p, exportOptions: { splitFiles: true } });
    for (const f of files.filter((f) => f.name !== '__init__.py')) expect(f.text.split('\n')[0]).toBe('from __future__ import annotations');
  });

  it('split into a package with sibling imports', () => {
    const files = generateFiles({ ...resnet(), exportOptions: { splitFiles: true } });
    expect(files.map((f) => f.name)).toEqual(['__init__.py', 'res_block.py', 'res_net.py']);
    expect(files[0]!.text).toContain('from .res_net import ResNet');
    expect(files[2]!.text).toContain('from .res_block import ResBlock');
    expect(files[1]!.text).not.toContain('from .');
  });

  it('are kept in the project file and checked when read', () => {
    const p = { ...resnet(), exportOptions: { nesting: 2, selfTest: true } };
    expect(parseProject(JSON.parse(JSON.stringify(p))).exportOptions).toEqual({ nesting: 2, selfTest: true });
    expect(() => parseProject({ ...JSON.parse(JSON.stringify(p)), exportOptions: { nesting: -1 } })).toThrow();
    expect(() => parseProject({ ...JSON.parse(JSON.stringify(p)), exportOptions: { selfTest: 'yes' } })).toThrow();
  });
});

// Runs every variant against the default code of the same project.
const SCRIPT = `
import json, os, sys, tempfile, torch
def load(name, src, class_name, main=False):
    module = type(sys)(name)
    if main:
        module.__dict__["__name__"] = "__main__"
    sys.modules[name] = module
    exec(src, module.__dict__)
    return module.__dict__[class_name]
results = []
for i, case in enumerate(json.load(sys.stdin)):
    try:
        torch.manual_seed(0)
        a = load(f"default_{i}", case["default"], case["className"])()
        if case.get("files"):
            root = tempfile.mkdtemp()
            package = os.path.join(root, f"pkg_{i}")
            os.mkdir(package)
            for f in case["files"]:
                with open(os.path.join(package, f["name"]), "w", encoding="utf-8") as out:
                    out.write(f["text"])
            sys.path.insert(0, root)
            b = getattr(__import__(f"pkg_{i}"), case["className"])()
        else:
            b = load(f"variant_{i}", case["variant"], case["className"], main=True)()
        a.eval(); b.eval()
        if sorted(a.state_dict()) != sorted(b.state_dict()):
            results.append("state_dict keys differ"); continue
        b.load_state_dict(a.state_dict())
        inputs = [torch.randn([int(d) if d.isdigit() else 2 for d in s.split(",")]) for s in case["inputs"]]
        with torch.no_grad():
            oa, ob = a(*inputs), b(*inputs)
        oa = oa if isinstance(oa, tuple) else (oa,)
        ob = ob if isinstance(ob, tuple) else (ob,)
        results.append(len(oa) == len(ob) and all(torch.allclose(x, y) for x, y in zip(oa, ob)))
    except Exception as e:
        results.append(f"{type(e).__name__}: {e}")
print(json.dumps(results))
`;

describe.skipIf(!hasTorch)('export options keep the model the same', () => {
  const cases = Object.entries(FIXTURES).flatMap(([fixture, make]) => [
    ...Object.entries(VARIANTS).map(([variant, options]) => ({ name: `${fixture} ${variant}`, project: make(), options, split: false })),
    { name: `${fixture} split`, project: make(), options: { splitFiles: true, selfTest: true } as ExportOptions, split: true },
  ]);
  let results: (boolean | string)[] = [];

  beforeAll(() => {
    const input = cases.map((c) => {
      const p = { ...c.project, exportOptions: c.options };
      return {
        default: generateCode(c.project).code,
        variant: c.split ? undefined : generateCode(p).code,
        files: c.split ? generateFiles(p) : undefined,
        className: entryModule(c.project).className,
        inputs: Object.values(inputShapesOf(c.project)).map((s) => s.split(':')[0]),
      };
    });
    results = JSON.parse(runPython(['-c', SCRIPT], JSON.stringify(input)));
  }, 120_000);

  cases.forEach((c, i) => {
    it(c.name, () => {
      expect(results[i]).toBe(true);
    });
  });

  it('nested code reads back as the same graph', { timeout: 60_000 }, () => {
    const projects = [resnet(), mlp()];
    const again = importMany(projects.map((p) => ({ source: code(p, { nesting: 3 }), inputShapes: inputShapesOf(p) })));
    projects.forEach((p, i) => expect(generateCode(parseProject(again[i]!.project)).code).toBe(generateCode(p).code));
  });

  it('analysis is unaffected', () => {
    const p = resnet();
    expect(analyzeProject({ ...p, exportOptions: VARIANTS.everything }).entry.totalParams).toBe(analyzeProject(p).entry.totalParams);
  });
});
