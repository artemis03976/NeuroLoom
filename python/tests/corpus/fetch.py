"""Downloads the third-party corpus files listed in manifest.json into third_party/<id>/.

Each file comes from raw.githubusercontent.com at the commit the manifest pins, together
with the repository's license, and must match the recorded sha256. The files are
committed, so the tests never download anything; run this only to add a file or move
one to another commit (--update records the new hashes).

    python tests/corpus/fetch.py [--update] [id ...]
"""
import hashlib
import json
import sys
import urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent
THIRD_PARTY = HERE / "third_party"


def download(repo: str, commit: str, path: str) -> bytes:
    url = f"https://raw.githubusercontent.com/{repo}/{commit}/{path}"
    with urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": "neuroloom-corpus"}), timeout=60) as r:
        return r.read()


def notices(manifest: list[dict]) -> str:
    """THIRD_PARTY_NOTICES.md: where every file comes from and under which license."""
    lines = [
        "# Third-party notices",
        "",
        "`third_party/<id>/` holds files from the repositories below, unmodified, at the",
        "commit given, each with its repository's license file. They are test data for",
        "NeuroLoom's importer and are not part of NeuroLoom. Generated by `fetch.py --update`",
        "from manifest.json.",
        "",
        "| id | repository | commit | license | license file |",
        "| --- | --- | --- | --- | --- |",
    ]
    for e in sorted(manifest, key=lambda e: e["id"]):
        lines.append(f"| {e['id']} | [{e['repo']}](https://github.com/{e['repo']}) | `{e['commit'][:12]}` | {e['license']} | `third_party/{e['id']}/{e['licenseFile']}` |")
    return "\n".join(lines) + "\n"


def main() -> None:
    args = sys.argv[1:]
    update = "--update" in args
    ids = [a for a in args if a != "--update"]
    manifest_path = HERE / "manifest.json"
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    for entry in manifest:
        if ids and entry["id"] not in ids:
            continue
        folder = THIRD_PARTY / entry["id"]
        hashes = entry.setdefault("sha256", {})
        for path in [*entry["files"], entry["licenseFile"]]:
            data = download(entry["repo"], entry["commit"], path)
            digest = hashlib.sha256(data).hexdigest()
            if hashes.get(path) != digest:
                if not update:
                    raise SystemExit(f"{entry['id']}: {path} has sha256 {digest}, the manifest records {hashes.get(path)}")
                hashes[path] = digest
            target = folder / path
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(data)
        print(f"{entry['id']}: {len(entry['files'])} file(s) at {entry['commit'][:8]}")
    if update:
        manifest_path.write_text(json.dumps(manifest, ensure_ascii=False, indent=1) + "\n", encoding="utf-8", newline="\n")
        (HERE / "THIRD_PARTY_NOTICES.md").write_text(notices(manifest), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
